/* The repo types web-standard globals only, so the runner's env is read off globalThis. */
const env =
  (globalThis as { process?: { env?: Record<string, string | undefined> } }).process?.env ?? {};

/** Minutes in the month every monthly figure is given for: thirty days. */
const MINUTES_PER_MONTH = 30 * 24 * 60;

/** Deploy bursts the report measures, all at profile M. */
const BURSTS = [5, 30, 50];

/**
 * Published per-million request prices, as of the date below.
 *
 * ILLUSTRATIVE AND ROUNDED. They are here so the operation counts land in the
 * unit an operator budgets in, not so anyone quotes this table: check the
 * provider's own page before deciding anything with it. Deletions are free at
 * all three, so they are counted and never priced.
 */
const PRICES_AS_OF = "2026-09-19";

interface PricePoint {
  name: string;
  /** PUT, COPY, POST and LIST, per million. */
  classA: number;
  /** GET and HEAD, per million. */
  classB: number;
  note: string;
}

const PRICES: PricePoint[] = [
  {
    name: "AWS S3 Standard",
    classA: 5,
    classB: 0.4,
    note: "us-east-1; DELETE is not charged",
  },
  {
    name: "Cloudflare R2",
    classA: 4.5,
    classB: 0.36,
    note: "class A / class B as R2 defines them; DELETE is class A but not charged",
  },
  {
    name: "Backblaze B2",
    classA: 4,
    classB: 0.4,
    note: "uploads are free; the class A column here is B2's class C (LIST), the class B column is downloads and HEAD",
  },
];

interface ProfileReport {
  profile: ScaleProfile;
  keys: number;
  seedMs: number;
  results: ScenarioResult[];
}

await main();

async function main(): Promise<void> {
  const remote = (env.SCAFO_SCALE_STORE ?? "") === "s3";
  const lines: string[] = [];
  const reports: ProfileReport[] = [];

  for (const name of wantedProfiles()) {
    reports.push(await measureProfile(name, remote));
  }

  progress("measuring deploy bursts at M");
  const bursts: BurstOutcome[] = [];
  for (const deploys of BURSTS) {
    const world = await createScaleWorld(
      PROFILES.M,
      await storeOptions(remote, `burst-${String(deploys)}`),
    );
    bursts.push(await deployBurst(world, { deploys }));
  }

  lines.push(
    `# scafo scale report`,
    ``,
    `Every number below is measured: each scenario drives the real code against a`,
    `metered \`CasStore\`, and the meter counts what a bucket would have been asked`,
    `for. Store: **${remote ? "S3 (uns3 driver)" : "in-memory"}**. Generated by \`pnpm scale\`.`,
    ``,
    `A listing costs one request per thousand keys, so listings are reported as`,
    `PAGES rather than calls.`,
    ``,
  );

  for (const report of reports) lines.push(...profileSection(report, remote));
  lines.push(...steadyStateSection(reports));
  lines.push(...beforeSection(reports));
  lines.push(...burstSection(bursts));
  lines.push(...footer());

  console.log(lines.join("\n"));
}

/**
 * The profiles this run measures: all of them, or the ones
 * `SCAFO_SCALE_PROFILES` names — which is how a run against a real bucket asks
 * for one size rather than paying for four.
 */
function wantedProfiles(): ProfileName[] {
  const asked = (env.SCAFO_SCALE_PROFILES ?? "").trim();
  if (asked === "") return [...PROFILE_NAMES];

  return asked.split(",").map((name) => {
    const wanted = name.trim().toUpperCase() as ProfileName;
    if (!PROFILE_NAMES.includes(wanted)) {
      throw new Error(`no profile "${name.trim()}"; they are ${PROFILE_NAMES.join(", ")}`);
    }
    return wanted;
  });
}

/** Runs every scenario of one profile, seeding an installation for it first. */
async function measureProfile(name: ProfileName, remote: boolean): Promise<ProfileReport> {
  const profile = PROFILES[name];
  progress(
    `seeding ${name}: ${String(profile.applications)} applications, ${String(profile.nodes)} nodes`,
  );
  const startedSeed = performance.now();
  const world = await createScaleWorld(profile, await storeOptions(remote, name.toLowerCase()));
  const seedMs = performance.now() - startedSeed;
  progress(`  seeded ${String(world.seed.keys)} objects in ${ms(seedMs)}`);

  const results: ScenarioResult[] = [];
  for (const scenario of SCENARIOS) {
    progress(`  ${name} ${scenario}`);
    results.push(await runScenario(scenario as ScenarioName, world));
  }
  await cleanUp(world, remote);
  return { profile, keys: world.seed.keys, seedMs, results };
}

/** Where a profile's installation is written: memory, or a prefix of its own in the bucket. */
async function storeOptions(
  remote: boolean,
  label: string,
): Promise<{ store?: CasStore; concurrency?: number }> {
  if (!remote) return {};

  const endpoint = required("S3_ENDPOINT");
  const client = new S3Client({
    endpoint,
    region: env.S3_REGION ?? "us-east-1",
    credentials: {
      accessKeyId: required("S3_ACCESS_KEY"),
      secretAccessKey: required("S3_SECRET_KEY"),
    },
    bucketStyle: "path",
    defaultBucket: required("S3_BUCKET"),
  });
  /* A prefix of its own per run, so a report never reads or deletes anything
     another run — or the integration suite — put in the bucket. */
  const prefix = `scale/${label}/${randomHex(8)}`;
  return {
    store: createUns3Store(client, { bucket: required("S3_BUCKET"), prefix }),
    concurrency: 16,
  };
}

/** Removes everything a remote run wrote; an in-memory one has nothing to remove. */
async function cleanUp(world: ScaleWorld, remote: boolean): Promise<void> {
  if (!remote) return;
  progress("  removing what this profile wrote");
  const keys = await world.store.list("");
  for (const key of keys) await world.store.del(key);
}

function profileSection(report: ProfileReport, remote: boolean): string[] {
  const profile = report.profile;
  const header = [
    `| scenario | LIST pages | GET | PUT | DEL | bytes read | bytes written | peak |`,
    `| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |`,
  ];
  const rows = report.results.map((result) => {
    const s = result.snapshot;
    const cells = [
      result.scenario,
      String(s.listPages),
      String(s.gets),
      String(s.puts),
      String(s.dels),
      bytes(s.bytesRead),
      bytes(s.bytesWritten),
      String(s.peakInFlight),
    ];
    if (remote) cells.push(ms(result.wallMs));
    return `| ${cells.join(" | ")} |`;
  });
  if (remote) {
    header[0] = `${header[0] as string} wall |`;
    header[1] = `${header[1] as string} ---: |`;
  }

  return [
    `## Profile ${profile.name}`,
    ``,
    `${String(profile.applications)} applications on ${String(profile.nodes)} node(s), replicas ` +
      `\`${String(profile.replicas)}\`, ${String(profile.deploymentsKept)} deployments and ` +
      `${String(profile.deployRecords)} deploy records per application, ` +
      `${String(profile.trustPolicies)} trust policies, ` +
      `${String(profile.domainsPerApplication ?? 0)} custom domain(s) per application. ` +
      `${String(report.keys)} objects, seeded in ${ms(report.seedMs)}.`,
    ``,
    ...header,
    ...rows,
    ``,
    ...notesLines(report),
    ``,
  ];
}

/** What each scenario observed beyond the store, which is half of what a number means. */
function notesLines(report: ProfileReport): string[] {
  return report.results.map((result) => {
    const notes = Object.entries(result.notes)
      .map(([name, value]) => `${name}=${String(value)}`)
      .join(", ");
    return `- \`${result.scenario}\`: ${notes}`;
  });
}

function steadyStateSection(reports: ProfileReport[]): string[] {
  const perMinute = cadences();

  const lines = [
    `## Steady state: an installation with nobody deploying`,
    ``,
    `Cadences are the code's own defaults:`,
    ``,
    `| loop | interval | per minute |`,
    `| --- | ---: | ---: |`,
    `| reconcile pass (every node) | ${String(DEFAULT_RECONCILE_INTERVAL_MS / 1000)}s | ${String(perMinute.reconcile + perMinute.nodeRefresh + perMinute.resync)} |`,
    `| — of those, one that re-reads the node records | ${String(DEFAULT_NODE_REFRESH_INTERVAL_MS / 1000)}s | ${String(perMinute.nodeRefresh)} |`,
    `| — of those, one that re-reads everything | ${String(DEFAULT_REGISTRY_RESYNC_MS / 1000)}s | ${String(perMinute.resync)} |`,
    `| heartbeat (every node) | ${String(NODE_HEARTBEAT_INTERVAL_MS / 1000)}s | ${String(perMinute.heartbeat)} |`,
    `| coordinator tick: lease renewal + assignment pass (one node) | ${String(Math.floor(DEFAULT_LEASE_TTL_MS / 3) / 1000)}s | ${String(perMinute.coordinatorTick)} |`,
    `| reap (the coordinator, on its tick) | ${String(DEFAULT_REAP_INTERVAL_MS / 1000)}s | ${String(perMinute.reap)} |`,
    `| observation flush | ${String(OBSERVE_FLUSH_INTERVAL_MS / 1000)}s | 0 — observability is off unless an operator turns it on |`,
    ``,
    `A reconcile pass reads ONE object — the change hint — and stops there unless`,
    `the token moved or one of its own timers is up. A coordinator tick renews the`,
    `lease with one conditional PUT and skips the assignment pass entirely when`,
    `nothing it decides from has changed. Idle means nothing changes, so no`,
    `placement is rewritten and no record is deleted.`,
    ``,
    `| profile | class A / node / min | class B / node / min | class A / month | class B / month | DELETE / month |`,
    `| --- | ---: | ---: | ---: | ---: | ---: |`,
  ];

  const monthly = new Map<ProfileName, { classA: number; classB: number }>();
  for (const report of reports) {
    const idle = idleCost(report, perMinute);
    monthly.set(report.profile.name, {
      classA: idle.installationClassA * MINUTES_PER_MONTH,
      classB: idle.installationClassB * MINUTES_PER_MONTH,
    });
    lines.push(
      `| ${report.profile.name} | ${round(idle.nodeClassA)} | ${round(idle.nodeClassB)} | ` +
        `${count(idle.installationClassA * MINUTES_PER_MONTH)} | ` +
        `${count(idle.installationClassB * MINUTES_PER_MONTH)} | ` +
        `${count(idle.installationDeletes * MINUTES_PER_MONTH)} |`,
    );
  }

  lines.push(
    ``,
    `"per node" is an ordinary node: its reconcile passes and its heartbeats. The`,
    `monthly figures are the whole installation — every node, plus the one node`,
    `that also coordinates and reaps — over ${String(MINUTES_PER_MONTH)} minutes.`,
    ``,
    `### What that costs, on three published price points`,
    ``,
    `**ASSUMPTIONS, stated as of ${PRICES_AS_OF} and rounded.** Class A is`,
    `PUT/COPY/POST/LIST; class B is GET/HEAD. Verify against the provider before`,
    `budgeting with any of it.`,
    ``,
    `| provider | class A per million | class B per million | note |`,
    `| --- | ---: | ---: | --- |`,
    ...PRICES.map(
      (price) =>
        `| ${price.name} | $${price.classA.toFixed(2)} | $${price.classB.toFixed(2)} | ${price.note} |`,
    ),
    ``,
    `Monthly request cost of an IDLE installation, requests only — storage,`,
    `egress and anything anyone deploys are all extra:`,
    ``,
    `| profile | ${PRICES.map((price) => price.name).join(" | ")} |`,
    `| --- | ${PRICES.map(() => "---:").join(" | ")} |`,
    ...[...monthly].map(
      ([name, cost]) =>
        `| ${name} | ` +
        PRICES.map(
          (price) =>
            `$${((cost.classA / 1_000_000) * price.classA + (cost.classB / 1_000_000) * price.classB).toFixed(2)}`,
        ).join(" | ") +
        ` |`,
    ),
    ``,
  );
  return lines;
}

/**
 * How often each measured pass runs in one minute.
 *
 * A reconcile pass is ONE loop with three costs: the ordinary pass that reads
 * the change hint and stops, the one on which the node records come due, and the
 * one on which everything is listed again. They are counted apart because they
 * cost different amounts, and together they are every pass the loop runs.
 */
function cadences(): {
  reconcile: number;
  nodeRefresh: number;
  resync: number;
  heartbeat: number;
  coordinatorTick: number;
  reap: number;
} {
  const passes = 60_000 / DEFAULT_RECONCILE_INTERVAL_MS;
  const nodeRefresh = 60_000 / DEFAULT_NODE_REFRESH_INTERVAL_MS;
  const resync = 60_000 / DEFAULT_REGISTRY_RESYNC_MS;
  return {
    reconcile: Math.max(0, passes - nodeRefresh - resync),
    nodeRefresh,
    resync,
    heartbeat: 60_000 / NODE_HEARTBEAT_INTERVAL_MS,
    coordinatorTick: 60_000 / Math.max(1, Math.floor(DEFAULT_LEASE_TTL_MS / 3)),
    reap: 60_000 / DEFAULT_REAP_INTERVAL_MS,
  };
}

/** What one minute of an idle installation costs, per node and altogether. */
function idleCost(
  report: ProfileReport,
  perMinute: ReturnType<typeof cadences>,
): {
  nodeClassA: number;
  nodeClassB: number;
  installationClassA: number;
  installationClassB: number;
  installationDeletes: number;
} {
  const of = (scenario: string): MeterSnapshot => {
    const found = report.results.find((result) => result.scenario === scenario);
    if (found === undefined) throw new Error(`"${scenario}" was not measured`);
    return found.snapshot;
  };
  const classA = (snapshot: MeterSnapshot): number => snapshot.puts + snapshot.listPages;
  const classB = (snapshot: MeterSnapshot): number => snapshot.gets;

  const reconcile = of("idleReconcilePass");
  const refresh = of("nodeRefreshPass");
  const resync = of("resyncPass");
  const beat = of("heartbeat");
  const assign = of("coordinatorAssignPass");
  /* The sweep AFTER the first: a terminal deploy record never moves again, so
     from the second pass onward the sweep lists the history and reads none of
     it, and that is what a running coordinator costs. */
  const reap = of("reapPassAgain");

  const perPass = (measure: (snapshot: MeterSnapshot) => number): number =>
    perMinute.reconcile * measure(reconcile) +
    perMinute.nodeRefresh * measure(refresh) +
    perMinute.resync * measure(resync);

  const nodeClassA = perPass(classA) + perMinute.heartbeat * classA(beat);
  const nodeClassB = perPass(classB) + perMinute.heartbeat * classB(beat);
  /* The lease renewal is already in what the tick measured. */
  const coordinatorClassA =
    perMinute.coordinatorTick * classA(assign) + perMinute.reap * classA(reap);
  const coordinatorClassB =
    perMinute.coordinatorTick * classB(assign) + perMinute.reap * classB(reap);

  return {
    nodeClassA,
    nodeClassB,
    installationClassA: nodeClassA * report.profile.nodes + coordinatorClassA,
    installationClassB: nodeClassB * report.profile.nodes + coordinatorClassB,
    installationDeletes:
      perPass((snapshot) => snapshot.dels) +
      perMinute.heartbeat * beat.dels +
      perMinute.coordinatorTick * assign.dels +
      perMinute.reap * reap.dels,
  };
}

/**
 * The same monthly figures for the build that read the whole installation on
 * every pass, so the improvement is a table rather than a claim.
 *
 * The numbers are FROZEN FORMULAS, not measurements: nothing here drives that
 * code, because it no longer exists. See `test/scale/_before.ts`.
 */
function beforeSection(reports: ProfileReport[]): string[] {
  const lines = [
    `### What it cost before`,
    ``,
    `Before the change hint, the registry view and the cached sweep, every`,
    `periodic pass read the whole installation to find out that nothing had`,
    `changed. The deploy queue admitted ${String(PAST_QUEUED_TASKS)} deploys and refused the rest.`,
    ``,
    `| profile | class A / month, before | after | class B / month, before | after |`,
    `| --- | ---: | ---: | ---: | ---: |`,
  ];

  const perMinute = cadences();
  for (const report of reports) {
    const shape = {
      applications: report.profile.applications,
      nodes: report.profile.nodes,
      deployRecords: report.profile.deployRecords,
    };
    const past = pastIdleCost(shape);
    const now = idleCost(report, perMinute);
    lines.push(
      `| ${report.profile.name} | ` +
        `${count(past.classA * MINUTES_PER_MONTH)} | ` +
        `${count(now.installationClassA * MINUTES_PER_MONTH)} | ` +
        `${count(past.classB * MINUTES_PER_MONTH)} | ` +
        `${count(now.installationClassB * MINUTES_PER_MONTH)} |`,
    );
  }

  lines.push(
    ``,
    `The cadences moved too: the coordinator lease went from`,
    `${String(PAST_CADENCES.coordinatorTickMs / 1000)}s to ${String(Math.floor(DEFAULT_LEASE_TTL_MS / 3) / 1000)}s between renewals, and the reap from`,
    `${String(PAST_CADENCES.reapIntervalMs / 1000)}s to ${String(DEFAULT_REAP_INTERVAL_MS / 1000)}s between sweeps.`,
    ``,
  );
  return lines;
}

function burstSection(bursts: BurstOutcome[]): string[] {
  return [
    `## A burst of concurrent deploys`,
    ``,
    `\`n\` deploys of \`n\` different applications, started together against ONE node's`,
    `deploy service at its default bounds — ${String(DEFAULT_QUEUED_TASKS)} queued deploys node-wide,`,
    `${String(DEFAULT_APPLICATION_QUEUED_TASKS)} per application, ${String(DEFAULT_ACTIVE_TASKS)} publishing at a time — with each`,
    `publish taking a fixed virtual ${String(bursts[0]?.durationMs ?? 0)}ms. Each deploy comes back`,
    `for a place in the queue when it is refused, through the very retry loop`,
    `\`scafo deploy\` runs; \`--no-wait\` is what fails instead.`,
    ``,
    `| n | accepted | deployed | refused | GET | PUT | LIST pages | CAS conflicts | peak in flight |`,
    `| ---: | ---: | ---: | --- | ---: | ---: | ---: | ---: | ---: |`,
    ...bursts.map((burst) => {
      const refused = Object.entries(burst.refused)
        .map(([code, times]) => `${String(times)}× \`${code}\``)
        .join(", ");
      return (
        `| ${String(burst.deploys)} | ${String(burst.accepted)} | ${String(burst.deployed)} | ` +
        `${refused === "" ? "none" : refused} | ${String(burst.snapshot.gets)} | ` +
        `${String(burst.snapshot.puts)} | ${String(burst.snapshot.listPages)} | ` +
        `${String(burst.snapshot.conflicts)} | ${String(burst.snapshot.peakInFlight)} |`
      );
    }),
    ``,
  ];
}


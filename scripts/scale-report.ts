/*
 * The scale report: what every periodic pass, every hot request and one burst
 * of deploys cost the bucket, at four sizes of installation.
 *
 * ONE MARKDOWN DOCUMENT ON STDOUT, and nothing else — progress goes to stderr,
 * so the report pipes into a file or a review unchanged. Nothing here reaches
 * the network unless `SCAFO_SCALE_STORE=s3` says so, and then only the bucket
 * the integration suite already uses.
 *
 * Run it with `pnpm scale`.
 */

